import { DomResolver } from "./dom-resolver";
import { LayoutPlanner, LayoutExecutionPlan } from "./layout-planner";
import { QGDS_BRAND_TOKENS } from "./qgds-tokens";
import { BrandThemeAdapter } from "./theme-adapter";
import { BaseBatchOptions } from "./types";

export interface PageFormatMetrics {
  name: string;
  type?: string;
  formatStr?: string;
  shortEdge: number;
  longEdge: number;
  margin: number;
  gutter: number;
  bleed: number;
  baseFont: number;
  masters: string[];
  scaleRatio?: number;
}

export interface LayoutEngineOptions extends BaseBatchOptions {
  adapter?: BrandThemeAdapter;
  formatOverride?: string;
  marginOverrideMm?: number;
  enforceStratification?: boolean;
  createMasters?: boolean;
  cleanMasters?: boolean;
  enforceMargins?: boolean;
  remapBodyPages?: boolean;
  injectFooters?: boolean;
  publicationTitle?: string;
}

export interface LayoutEngineReport {
  matchedFormat: string;
  dimensionsMm: { width: number; height: number };
  orientation: "portrait" | "landscape";
  scalingFactor: number;
  marginMm: number;
  mastersCreated: string[];
  pagesRemapped: number;
  footersInjected: number;
  skippedCount: number;
  details: string[];
}

const PT_TO_MM = LayoutPlanner.PT_TO_MM;

/**
 * Analyzes document dimensions in millimeters and matches against pageMatrix presets.
 */
export function analyzeDocumentMetrics(doc: any, customMatrix?: PageFormatMetrics[]): {
  metrics: PageFormatMetrics;
  widthMm: number;
  heightMm: number;
  orientation: "portrait" | "landscape";
} {
  let wPt = 595.28; // Default A4
  let hPt = 841.89;

  try {
    if (doc.pages && doc.pages.length > 0) {
      const p = doc.pages[0];
      const bounds = p.bounds || [0, 0, 841.89, 595.28];
      hPt = Math.abs(bounds[2] - bounds[0]);
      wPt = Math.abs(bounds[3] - bounds[1]);
    } else if (doc.documentPreferences) {
      wPt = doc.documentPreferences.pageWidth || 595.28;
      hPt = doc.documentPreferences.pageHeight || 841.89;
    }
  } catch (_) {}

  const { widthMm, heightMm, shortEdgeMm, longEdgeMm, orientation } = LayoutPlanner.analyzeDimensions(
    wPt,
    hPt
  );

  const matrix = customMatrix || (QGDS_BRAND_TOKENS.pageMatrix as unknown as PageFormatMetrics[]) || [];

  for (const preset of matrix) {
    if (
      Math.abs(shortEdgeMm - preset.shortEdge) <= 3 &&
      Math.abs(longEdgeMm - preset.longEdge) <= 3
    ) {
      return { metrics: preset, widthMm, heightMm, orientation };
    }
  }

  // Fallback for custom dimensions
  const fallbackMargin = Math.max(12, Math.round(shortEdgeMm * 0.05));
  const fallback: PageFormatMetrics = {
    name: "Custom",
    shortEdge: shortEdgeMm,
    longEdge: longEdgeMm,
    margin: fallbackMargin,
    gutter: fallbackMargin,
    bleed: 3,
    baseFont: 12,
    masters: ["Cover", "Content", "Back"]
  };

  return { metrics: fallback, widthMm, heightMm, orientation };
}

/**
 * Enterprise Layout Engine.
 * Executes decoupled geometry execution plans generated by LayoutPlanner.
 */
export class QgdsLayoutEngineService extends BaseService<LayoutEngineOptions, LayoutEngineReport> {
  protected actionName = "QGDS Layout & Master Spread Engine";

  protected process(doc: any, options: LayoutEngineOptions): LayoutEngineReport {
    doc.recompose();

    // 1. Read document dimensions in points
    let wPt = 595.28;
    let hPt = 841.89;
    let pageCount = 1;

    try {
      if (doc.pages && doc.pages.length > 0) {
        pageCount = doc.pages.length;
        const p = doc.pages[0];
        const bounds = p.bounds || [0, 0, 841.89, 595.28];
        hPt = Math.abs(bounds[2] - bounds[0]);
        wPt = Math.abs(bounds[3] - bounds[1]);
      } else if (doc.documentPreferences) {
        wPt = doc.documentPreferences.pageWidth || 595.28;
        hPt = doc.documentPreferences.pageHeight || 841.89;
      }
    } catch (_) {}

    // 2. Pure geometry planning
    const pubTitle =
      options.publicationTitle ||
      (doc.name ? String(doc.name).replace(/\.[^.]+$/, "") : "Queensland Government Publication");

    const plan: LayoutExecutionPlan = LayoutPlanner.calculatePlan({
      widthPt: wPt,
      heightPt: hPt,
      pageCount,
      publicationTitle: pubTitle,
      marginOverrideMm: options.marginOverrideMm,
      presets: QGDS_BRAND_TOKENS.pageMatrix as unknown as any[],
      adapter: options.adapter
    });

    const report: LayoutEngineReport = {
      matchedFormat: plan.matchedFormat,
      dimensionsMm: plan.dimensionsMm,
      orientation: plan.orientation,
      scalingFactor: plan.scalingFactor,
      marginMm: plan.marginMm,
      mastersCreated: [],
      pagesRemapped: 0,
      footersInjected: 0,
      skippedCount: 0,
      details: []
    };

    report.details.push(
      `Computed layout plan for: ${plan.matchedFormat} (${plan.dimensionsMm.width}x${plan.dimensionsMm.height}mm, ${plan.orientation}, margin: ${plan.marginMm}mm, grid: ${plan.baselineGridPt}pt).`
    );

    // 2b. Synchronize Document Baseline Grid
    if (!options.dryRun && doc.gridPreferences) {
      try {
        doc.gridPreferences.baselineDivision = plan.baselineGridPt;
        doc.gridPreferences.baselineStart = plan.marginPt;
      } catch (_) {}
    }

    // 3. Layer Stratification Execution
    if (options.enforceStratification !== false && doc.layers) {
      try {
        for (const req of plan.layers) {
          const l = DomResolver.getOrCreateLayer(doc, req.name);
          if (l && l.isValid) {
            try {
              l.locked = false;
              l.visible = true;
            } catch (_) {}
          }
        }
        report.details.push("Enforced layer stratification from layout plan.");
      } catch (err: any) {
        if (options.failurePolicy === "strict") throw err;
        report.skippedCount++;
      }
    }

    // 4. Master Spreads Creation / Adoption Execution
    const masterSpreadsMap: Record<string, any> = {};

    if (options.createMasters !== false && doc.masterSpreads) {
      try {
        for (const mPlan of plan.masterPlans) {
          let foundMaster: any = null;
          const currentMasters = doc.masterSpreads.everyItem
            ? doc.masterSpreads.everyItem().getElements()
            : [];

          // Exact match
          for (let m = 0; m < currentMasters.length; m++) {
            const cm = currentMasters[m];
            if (
              cm.isValid &&
              (cm.name === mPlan.fullName ||
                (cm.namePrefix === mPlan.prefix && cm.baseName === mPlan.baseName))
            ) {
              foundMaster = cm;
              break;
            }
          }

          // Adopt matching prefix
          if (!foundMaster) {
            for (let m = 0; m < currentMasters.length; m++) {
              const cm = currentMasters[m];
              if (cm.isValid && cm.namePrefix === mPlan.prefix) {
                try {
                  if (!options.dryRun) {
                    cm.baseName = mPlan.baseName;
                  }
                  foundMaster = cm;
                  report.mastersCreated.push(mPlan.fullName);
                  break;
                } catch (_) {}
              }
            }
          }

          // Create new master
          if (!foundMaster && !options.dryRun) {
            try {
              const newM = doc.masterSpreads.add();
              newM.namePrefix = mPlan.prefix;
              newM.baseName = mPlan.baseName;
              foundMaster = newM;
              report.mastersCreated.push(mPlan.fullName);
            } catch (_) {}
          }

          // Purge existing items on master pages if cleanMasters is enabled
          if (
            foundMaster &&
            foundMaster.isValid &&
            options.cleanMasters !== false &&
            !options.dryRun
          ) {
            const mPages = foundMaster.pages
              ? foundMaster.pages.everyItem
                ? foundMaster.pages.everyItem().getElements()
                : foundMaster.pages
              : [];
            for (let p = 0; p < mPages.length; p++) {
              const mp = mPages[p];
              if (!mp || !mp.isValid) continue;
              const pItems = mp.pageItems
                ? mp.pageItems.everyItem
                  ? mp.pageItems.everyItem().getElements()
                  : mp.pageItems
                : [];
              for (let pi = pItems.length - 1; pi >= 0; pi--) {
                const item = pItems[pi];
                if (item && item.isValid) {
                  try {
                    if (item.itemLayer && item.itemLayer.isValid && item.itemLayer.locked)
                      item.itemLayer.locked = false;
                    if (item.locked) item.locked = false;
                    item.remove();
                  } catch (_) {}
                }
              }
            }
          }

          masterSpreadsMap[mPlan.prefix] = foundMaster;
        }

        report.details.push(
          `Verified master spreads: ${plan.masterPlans.map(m => m.fullName).join(", ")}.`
        );
      } catch (err: any) {
        if (options.failurePolicy === "strict") throw err;
        report.skippedCount++;
      }
    }

    // 5. Margin & Gutter Enforcement Execution
    if (options.enforceMargins !== false && !options.dryRun) {
      try {
        // Enforce on Master Spreads from plan
        for (const mPlan of plan.masterPlans) {
          const ms = masterSpreadsMap[mPlan.prefix];
          if (!ms || !ms.isValid || !ms.pages) continue;

          const mPages = ms.pages.everyItem ? ms.pages.everyItem().getElements() : [];
          for (let p = 0; p < mPages.length; p++) {
            const pg = mPages[p];
            if (pg && pg.isValid && pg.marginPreferences) {
              pg.marginPreferences.properties = {
                top: `${mPlan.marginsMm.top}mm`,
                bottom: `${mPlan.marginsMm.bottom}mm`,
                left: `${mPlan.marginsMm.left}mm`,
                right: `${mPlan.marginsMm.right}mm`,
                columnGutter: `${mPlan.gutterMm}mm`
              };
            }
          }
        }

        // Enforce on Body Document Pages
        const docPages = doc.pages?.everyItem ? doc.pages.everyItem().getElements() : [];
        for (let p = 0; p < docPages.length; p++) {
          const pg = docPages[p];
          if (!pg || !pg.isValid || !pg.marginPreferences) continue;
          pg.marginPreferences.properties = {
            top: `${plan.marginMm}mm`,
            bottom: `${plan.marginMm}mm`,
            left: `${plan.marginMm}mm`,
            right: `${plan.marginMm}mm`,
            columnGutter: `${plan.gutterMm}mm`
          };
        }
        report.details.push(`Enforced ${plan.marginMm}mm margins and ${plan.gutterMm}mm gutter.`);
      } catch (err: any) {
        if (options.failurePolicy === "strict") throw err;
        report.skippedCount++;
      }
    }

    // 6. Remap Document Pages to Masters
    if (options.remapBodyPages !== false && !options.dryRun && doc.pages) {
      try {
        const docPages = doc.pages.everyItem ? doc.pages.everyItem().getElements() : [];
        for (const remap of plan.pageRemappings) {
          const pg = docPages[remap.pageIndex];
          const targetMaster = masterSpreadsMap[remap.targetMasterPrefix];
          if (pg && pg.isValid && targetMaster && targetMaster.isValid) {
            pg.appliedMaster = targetMaster;
            report.pagesRemapped++;
          }
        }

        // Remove unused empty default "A-Master" if Cover master exists
        const aCoverMaster = masterSpreadsMap["A"];
        if (aCoverMaster && aCoverMaster.isValid && doc.masterSpreads) {
          const masters = doc.masterSpreads.everyItem
            ? doc.masterSpreads.everyItem().getElements()
            : [];
          for (let m = masters.length - 1; m >= 0; m--) {
            const ms = masters[m];
            if (ms && ms.isValid && (ms.name === "A-Master" || ms.name === "A-Parent")) {
              const items = ms.pageItems?.everyItem
                ? ms.pageItems.everyItem().getElements()
                : ms.pageItems || [];
              if (items.length === 0) {
                try {
                  ms.remove();
                } catch (_) {}
              }
            }
          }
        }
        report.details.push(
          `Remapped ${report.pagesRemapped} body page(s) to master spreads.`
        );
      } catch (err: any) {
        if (options.failurePolicy === "strict") throw err;
        report.skippedCount++;
      }
    }

    // 7. Inject Folios from Plan
    if (options.injectFooters !== false && !options.dryRun) {
      try {
        for (const mPlan of plan.masterPlans) {
          if (!mPlan.folios || mPlan.folios.length === 0) continue;
          const ms = masterSpreadsMap[mPlan.prefix];
          if (!ms || !ms.isValid || !ms.pages) continue;

          const mPages = ms.pages.everyItem ? ms.pages.everyItem().getElements() : [];
          for (let pIdx = 0; pIdx < mPages.length; pIdx++) {
            const pageEl = mPages[pIdx];
            if (!pageEl || !pageEl.isValid || !pageEl.textFrames) continue;

            for (const folio of mPlan.folios) {
              // Locate or create folio layer
              let fLayer = doc.layers?.itemByName(folio.layerName);
              if (!fLayer || !fLayer.isValid) {
                fLayer = doc.layers ? doc.layers[0] : null;
              }

              // Purge existing folio frames to avoid duplicates
              if (pageEl.textFrames.everyItem) {
                const tfs = pageEl.textFrames.everyItem().getElements();
                for (let ti = tfs.length - 1; ti >= 0; ti--) {
                  if (
                    tfs[ti].label === folio.label ||
                    tfs[ti].label === "DynamicContentFooter" ||
                    tfs[ti].label === "DynamicBrandFooter" ||
                    tfs[ti].name === folio.name ||
                    tfs[ti].name === "DynamicBrandFooter"
                  ) {
                    try {
                      tfs[ti].remove();
                    } catch (_) {}
                  }
                }
              }

              const tfFolio = pageEl.textFrames.add({
                label: folio.label,
                name: folio.name,
                geometricBounds: folio.geometricBounds,
                itemLayer: fLayer
              });

              try {
                tfFolio.contents = folio.text;
              } catch (_) {}

              try {
                if (tfFolio.paragraphs && tfFolio.paragraphs[0]) {
                  tfFolio.paragraphs[0].pointSize = folio.pointSize;
                }
              } catch (_) {}

              report.footersInjected++;
            }
          }
        }
        report.details.push(`Injected folios from layout plan.`);
      } catch (err: any) {
        if (options.failurePolicy === "strict") throw err;
        report.skippedCount++;
      }
    }

    return report;
  }
}
